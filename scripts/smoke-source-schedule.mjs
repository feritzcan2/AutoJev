import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdtemp} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Store} from '../app/store.mjs';

const require=createRequire(import.meta.url);
const {_electron:electron}=createRequire(require.resolve('@playwright/mcp/package.json'))('playwright');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const data=await mkdtemp(path.join(os.tmpdir(),'jobloop-source-schedule-'));
const store=new Store(path.join(data,'jobloop.sqlite'));
const profile=store.saveProfile({name:'Schedule test',preferences:'Remote'}),sources=store.sources(profile.id);
const other=store.saveProfile({name:'Other candidate',preferences:'Berlin'});
store.saveSourcesInterval(other.id,90);
store.close();
const application=await electron.launch({executablePath:process.env.JOBLOOP_ELECTRON_BINARY||require('electron'),args:[root],env:{...process.env,JOBLOOP_DATA_DIR:data}});
try{
 const page=await application.firstWindow(),errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.waitForFunction(()=>document.querySelectorAll('#candidates option').length===3);
 await page.selectOption('#candidates',profile.id);
 await page.locator('button[data-view=sources]').click();
 const interval=page.locator('#sources-interval'),apply=page.getByRole('button',{name:'Tümüne uygula',exact:true});
 await interval.waitFor();assert.equal(await interval.inputValue(),'');
 assert.equal(await interval.getAttribute('placeholder'),'Farklı');
 await page.getByRole('button',{name:`${sources[0].name} kaynağını düzenle`,exact:true}).click();
 await page.locator('.source-editor [name=name]').fill('Edited source');
 await interval.fill('0');await apply.click();
 assert.equal(await interval.evaluate(input=>input.validity.valid),false);
 await interval.fill('120');await apply.click();
 await page.waitForFunction(()=>[...document.querySelectorAll('.source-plan b')].every(node=>node.textContent==='Her 120 dk'));
 assert.equal(await page.locator('.source-editor [name=intervalMinutes]').inputValue(),'120');
 assert.equal(await page.locator('.source-editor [name=name]').inputValue(),'Edited source');
 await page.locator('.source-editor button[type=submit]').click();
 await page.waitForFunction(()=>!document.querySelector('.source-editor'));
 const saved=await page.evaluate(id=>window.jobloop.workspaceSnapshot(id),profile.id);
 assert.ok(saved.sources.every(source=>source.intervalMinutes===120));
 assert.deepEqual(saved.sources.map(source=>source.enabled),sources.map(source=>source.enabled));
 assert.notEqual(saved.campaign?.status,'running');
 await page.reload();await page.locator('button[data-view=sources]').click();
 await page.waitForFunction(()=>document.querySelector('#sources-interval')?.value==='120');
 await interval.fill('45');
 await page.selectOption('#candidates',other.id);
 await page.waitForFunction(()=>document.querySelector('#sources-interval')?.value==='90');
 await page.selectOption('#candidates',profile.id);
 await page.waitForFunction(()=>document.querySelector('#sources-interval')?.value==='120');
 await page.locator('button[data-view=sources]').click();
 await interval.waitFor({state:'visible'});
 await page.screenshot({path:path.join(data,'sources-schedule.png')});
 assert.deepEqual(errors,[]);
 console.log('SOURCE_SCHEDULE_UI_PASS',data);
}finally{await application.close();}
