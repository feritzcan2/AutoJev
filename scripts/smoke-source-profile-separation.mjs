import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {WorkspaceDatabase} from '../app/workspace-database.mjs';
import {AutomationStore} from '../app/automation-store.mjs';

const require=createRequire(import.meta.url),{_electron:electron}=createRequire(require.resolve('@playwright/mcp/package.json'))('playwright');
const data=await mkdtemp(path.join(tmpdir(),'source-profile-separation-'));
const core=new WorkspaceDatabase(path.join(data,'jobloop.sqlite')),db=new AutomationStore(core);
const first='https://one.test/homes',second='https://two.test/homes',third='https://three.test/homes',manual='https://manual.test/homes';
const a=db.create('housing',{title:'Ev arama',goal:'Berlin’de uygun evleri bul',criteria:{location:'Berlin',budget:'1500',requirements:'2 oda'},sources:[first,second]});
db.review(a.id);const saved=db.get(a.id);
db.put({...saved,planDraft:{baseRevision:a.revision,runId:'legacy',updatedAt:Date.now(),plan:{title:a.title,goal:a.goal,criteria:{...a.criteria,budget:'1700'},instructions:a.instructions,facts:a.facts,sources:[first,third]}}});
core.close();
const env={...process.env,JOBLOOP_DATA_DIR:data};delete env.ELECTRON_RUN_AS_NODE;
const app=await electron.launch({executablePath:require('electron'),args:[process.cwd()],env});let page;
try{
 page=await app.firstWindow();page.setDefaultTimeout(10000);const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.waitForFunction(id=>document.querySelector('#candidates').value===id,a.id);
 const snapshot=()=>page.evaluate(id=>window.jobloop.workspaceSnapshot(id),a.id);
 await page.locator('[data-view=profile]').click();
 const profile=page.locator('#automation-plan-form');await profile.waitFor();
 assert.equal(await profile.locator('[name=sources]').count(),0);
 assert.doesNotMatch(await profile.innerText(),/Kaynak adresleri|Kaynaklar ve işleyiş/);
 assert.equal(await profile.locator('[name=criteria-budget]').inputValue(),'1700');
 await profile.locator('[name=instructions]').fill('Her ilanın kira tutarını doğrula.');
 await page.locator('[data-view=sources]').click();
 const sources=page.locator('[data-automation-pane=sources]');
 await sources.locator('.source-proposal').waitFor();
 assert.match(await sources.locator('.source-proposal').innerText(),/Eklenecek:.*three\.test/);
 assert.match(await sources.locator('.source-proposal').innerText(),/Kaldırılacak:.*two\.test/);
 await sources.getByRole('button',{name:'＋ Kaynak ekle',exact:true}).click();
 const form=sources.locator('.source-add');await form.locator('[name=name]').fill('Ek kaynak');await form.locator('[name=url]').fill(manual);
 await form.getByRole('button',{name:'Kaynağı ekle',exact:true}).click();
 await page.waitForFunction(async id=>(await window.jobloop.workspaceSnapshot(id)).automation.sources.includes('https://manual.test/homes'),a.id);
 assert.equal((await snapshot()).automation.reviewedRevision,a.revision);
 assert.doesNotMatch(await page.locator('#notice').innerText(),/profili kaydet/i);
 await page.locator('[data-view=profile]').click();
 assert.equal(await profile.locator('[name=instructions]').inputValue(),'Her ilanın kira tutarını doğrula.');
 await page.locator('#automation-profile-save').click();
 await page.waitForFunction(async id=>{const a=(await window.jobloop.workspaceSnapshot(id)).automation;return a.criteria.budget==='1700'&&!a.profileUpdate;},a.id);
 let state=await snapshot();assert.deepEqual(state.automation.sources,[first,second,manual]);assert.deepEqual(state.automation.sourceDraft.sources,[first,third,manual]);
 await page.screenshot({path:path.join(data,'profile.png'),fullPage:true});
 await page.locator('[data-view=setup-agent]').click();
 assert.equal(await page.getByRole('button',{name:'Taslağı incele ve kaydet',exact:true}).isVisible(),false);
 await page.getByRole('button',{name:'Kaynak önerilerini incele',exact:true}).click();
 await sources.locator('.source-proposal').waitFor();
 await page.screenshot({path:path.join(data,'sources.png'),fullPage:true});
 await sources.getByRole('button',{name:'Kaynak önerilerini uygula',exact:true}).click();
 await sources.locator('.source-proposal').waitFor({state:'hidden'});
 state=await snapshot();assert.deepEqual(state.automation.sources,[first,third,manual]);assert.equal(state.automation.criteria.budget,'1700');assert.equal(state.automation.reviewedRevision,state.automation.revision);
 const revision=state.automation.revision;
 const manualRow=sources.locator(`.source-row[data-source-id="${manual}"]`);
 await manualRow.getByRole('button',{name:'Düzenle',exact:true}).click();await manualRow.getByRole('button',{name:'Kaynağı kaldır',exact:true}).click();
 await manualRow.waitFor({state:'detached'});
 state=await snapshot();assert.deepEqual(state.automation.sources,[first,third]);assert.equal(state.automation.revision,revision);assert.equal(state.automation.reviewedRevision,revision);
 assert.deepEqual(errors,[]);console.log('SOURCE_PROFILE_SEPARATION_PASS',data);
}catch(error){if(page)await page.screenshot({path:path.join(data,'failure.png'),fullPage:true}).catch(()=>{});console.error('ARTIFACTS',data);throw error;}
finally{await app.close();}
