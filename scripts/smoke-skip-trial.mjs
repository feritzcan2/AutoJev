import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {WorkspaceDatabase} from '../app/workspace-database.mjs';
import {AutomationStore} from '../app/automation-store.mjs';
const require=createRequire(import.meta.url);
const {_electron:electron}=createRequire(require.resolve('@playwright/mcp/package.json'))('playwright');
const data=await mkdtemp(path.join(tmpdir(),'jobloop-skip-trial-'));
const core=new WorkspaceDatabase(path.join(data,'jobloop.sqlite')),db=new AutomationStore(core);
const owner=db.create('housing',{title:'Deneme atlama testi',goal:'Berlin evleri',criteria:{location:'Berlin',budget:'1500 EUR',requirements:'2 oda'},sources:['https://example.com/homes']});
db.review(owner.id);core.close();
const app=await electron.launch({executablePath:process.env.JOBLOOP_ELECTRON_BINARY||require('electron'),args:[process.cwd()],env:{...process.env,JOBLOOP_DATA_DIR:data}});
try{
 const page=await app.firstWindow(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.locator('[data-view=agent]').click();
 const skip=page.locator('[data-progress-action=skip-trial]');
 await skip.waitFor();await skip.click();
 await page.waitForFunction(()=>document.querySelector('#now-title').textContent==='Deneme atlandı');
 await page.getByRole('button',{name:'Düzenli takibi başlat',exact:true}).first().waitFor();
 const saved=await page.evaluate(id=>window.jobloop.workspaceSnapshot(id),owner.id);
 assert.equal(saved.automation.trial.status,'skipped');assert.equal(saved.automation.status,'ready');
 assert.equal(saved.activeRun,null);assert.equal(saved.runs.length,0);
 assert.equal(saved.progress.stage,2);assert.equal(await skip.count(),0);
 await page.locator('[data-view=profile]').click();
 await page.locator('#automation-plan-form [name=goal]').fill('Updated housing preferences');
 await page.getByRole('button',{name:'Profili kaydet',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#notice').textContent==='Profil kaydedildi. Yeniden deneme yapmadan devam edebilirsin.');
 const edited=await page.evaluate(id=>window.jobloop.workspaceSnapshot(id),owner.id);
 assert.equal(edited.automation.trial.status,'skipped');assert.equal(edited.progress.passed,true);assert.equal(edited.runs.length,0);
 await page.locator('[data-view=agent]').click();
 await page.waitForFunction(()=>document.querySelector('#now-title').textContent==='Deneme atlandı');
 await page.screenshot({path:path.join(data,'skip-trial.png'),fullPage:true});
 await page.reload();await page.locator('[data-view=agent]').click();
 await page.waitForFunction(()=>document.querySelector('#now-title').textContent==='Deneme atlandı');
 assert.deepEqual(errors,[]);console.log('SKIP_TRIAL_UI_PASS',data);
}finally{await app.close();}
